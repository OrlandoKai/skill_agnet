def main() -> None:
    seed_tasks = json.loads(MINI_PATH.read_text(encoding="utf-8"))
    all_tasks = seed_tasks + NEW_DEV_TASKS
    task_ids = [task["task_id"] for task in all_tasks]
    duplicates = [task_id for task_id, count in Counter(task_ids).items() if count > 1]
    if duplicates:
        raise SystemExit(f"Duplicate task_id values: {duplicates}")

    DEV_PATH.write_text(
        json.dumps(all_tasks, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    counts = Counter(task["task_type"] for task in all_tasks)
    print(f"Wrote {len(all_tasks)} tasks to {DEV_PATH}")
    print(f"Counts: {dict(counts)}")
    print(f"Added dev tasks: {NEW_DEV_TASKS[0]['task_id']} - {NEW_DEV_TASKS[-1]['task_id']}")


if __name__ == "__main__":
    main()
