def tool_task(
    task_id: str,
    instruction: str,
    gold_skills: list[str],
    expected_answer: str,
    task_type: str,
    notes: str,
    difficulty: str,
    benchmark_tags: list[str],
    source_inspiration: str,
    hard_negative_skills: list[str],
    argument_checks: list[dict],
    observation_checks: list[dict],
    final_answer_check: dict,
) -> dict:
    return {
        "task_id": task_id,
        "instruction": instruction,
        "gold_skills": gold_skills,
        "expected_answer": expected_answer,
        "task_type": task_type,
        "notes": notes,
        "gold_sequence": list(gold_skills),
        "difficulty": difficulty,
        "benchmark_tags": benchmark_tags,
        "source_inspiration": source_inspiration,
        "hard_negative_skills": hard_negative_skills,
        "expected_checks": {
            "arguments": argument_checks,
            "observations": observation_checks,
            "final_answer": final_answer_check,
            "faithfulness": True,
        },
    }


def abstain_task(
    task_id: str,
    instruction: str,
    expected_answer: str,
    task_type: str,
    notes: str,
    difficulty: str,
    benchmark_tags: list[str],
    source_inspiration: str,
    hard_negative_skills: list[str],
    final_answer_check: dict,
) -> dict:
    return {
        "task_id": task_id,
        "instruction": instruction,
        "gold_skills": [],
        "expected_answer": expected_answer,
        "task_type": task_type,
        "notes": notes,
        "gold_sequence": [],
        "difficulty": difficulty,
        "benchmark_tags": benchmark_tags,
        "source_inspiration": source_inspiration,
        "hard_negative_skills": hard_negative_skills,
        "expected_checks": {
            "final_answer": final_answer_check,
            "faithfulness": True,
        },
    }


